import 'dart:convert';
import 'dart:io';

const String _fontFamily = 'Feather';
const String _fontPackage = 'feather_icons';

String _camelCase(String value) {
  final parts = value.split('-');
  return parts.first + parts.skip(1).map((part) => part[0].toUpperCase() + part.substring(1)).join();
}

String _snakeCase(String value) => value.replaceAll('-', '_');

String _iconData(String codePoint) =>
    "IconData(0x$codePoint, fontFamily: '$_fontFamily', "
    "fontPackage: '$_fontPackage', matchTextDirection: true)";

Never _usage() {
  stderr.writeln('Usage: dart run tool/generate_fonts.dart <icons.json>');
  exit(64);
}

void main(List<String> args) {
  if (args.length != 1) {
    _usage();
  }

  final configFile = File(args.single);
  if (!configFile.existsSync()) {
    stderr.writeln('Config file not found: ${configFile.path}');
    exit(66);
  }

  final decoded = (jsonDecode(configFile.readAsStringSync()) as List<dynamic>).cast<Map<String, dynamic>>();
  final icons = <MapEntry<String, String>>[];
  for (final icon in decoded) {
    icon.forEach((name, codePoint) {
      icons.add(MapEntry(name, codePoint as String));
    });
  }

  final output = StringBuffer()
    ..writeln('// ignore_for_file: constant_identifier_names')
    ..writeln()
    ..writeln('library feather_icons;')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln()
    ..writeln('// THIS FILE IS AUTOMATICALLY GENERATED. DO NOT EDIT.')
    ..writeln()
    ..writeln('/// Feather icons indexed by their kebab-case names.')
    ..writeln('const Map<String, IconData> FeatherIconsMap = {');

  for (final icon in icons) {
    output.writeln("  '${icon.key}': ${_iconData(icon.value)},");
  }

  output
    ..writeln('};')
    ..writeln()
    ..writeln('/// Feather icons exposed as camelCase constants.')
    ..writeln('@staticIconProvider')
    ..writeln('abstract final class FeatherIcons {');

  for (final icon in icons) {
    output.writeln('  static const IconData ${_camelCase(icon.key)} = ${_iconData(icon.value)};');
  }

  output
    ..writeln('}')
    ..writeln()
    ..writeln('/// Feather icons exposed as snake_case constants.')
    ..writeln('@staticIconProvider')
    ..writeln('abstract final class FeatherIconsSnakeCase {');

  for (final icon in icons) {
    output.writeln('  static const IconData ${_snakeCase(icon.key)} = ${_iconData(icon.value)};');
  }

  output.writeln('}');
  File('lib/feather_icons.dart').writeAsStringSync(output.toString());
}
